/// 查询候选词的 emoji（词 → emoji 字符串）。无命中返回 None。
pub fn lookup(word: &str) -> Option<&'static str> {
    EMOJI_TABLE
        .iter()
        .find(|(w, _)| *w == word)
        .map(|(_, e)| *e)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lookup_common() {
        assert_eq!(lookup("喜欢"), Some("😍"));
        assert_eq!(lookup("谢谢"), Some("🙏"));
        assert_eq!(lookup("加油"), Some("💪"));
    }

    #[test]
    fn test_lookup_miss() {
        assert_eq!(lookup("桌子"), None);
        assert_eq!(lookup(""), None);
    }

    #[test]
    fn test_table_size() {
        assert!(
            EMOJI_TABLE.len() >= 100,
            "emoji 表应 >= 100, got {}",
            EMOJI_TABLE.len()
        );
    }
}
