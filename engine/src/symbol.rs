    #[test]
    fn test_query_arrow() {
        let s = query("jt");
        // 雾凇全量箭头表（顺序对齐 rime symbols_v.yaml）
        assert!(s.contains(&"↑") && s.contains(&"↓") && s.contains(&"←") && s.contains(&"→"));
        assert!(s.contains(&"↔") && s.contains(&"⇒") && s.contains(&"➜") && s.contains(&"↵"));
        assert!(s.len() >= 100, "箭头符号应 >= 100, got {}", s.len());
    }

